//! 语义召回的接口位 —— 向量/LLM 的那一半从这里接进来。
//!
//! 本 crate **不提供任何实现**，也不依赖任何模型或网络。这是有意的分工：
//!
//! * 召回 (recall) 可以用向量：它决定「哪些指标值得看一眼」，错了只是多看几个。
//! * 承诺 (precision) 不用向量：最终落到哪个指标，只认「这个词确实出现在指标的
//!   名字或同义词里」这种可以逐字核对的证据。一个 0.83 的余弦相似度没法向任何人
//!   解释为什么它比 0.81 更对，而这一步选错的代价是一个跑得干干净净的错数字。
//!
//! 所以没有实现的时候，grounding 退化成**纯词法召回**：这是可用的降级，不是缺陷。
//! 只要模型把中文同义词写全（`synonyms: [营收, 营业额, 流水]`），词法这一半就能
//! 独立落地；向量补的是长尾——同义词没写全时，「进账」也能找到 revenue。

/// 给 (问题, 文档) 打一个语义相似度分。
///
/// `docs` 与调用方的指标顺序一一对应，返回值必须等长；长度不符时上层会忽略这个
/// 信号而不是猜——退化到词法总比错位打分强。
///
/// 分数量纲不限（余弦、内积、rerank 打分都行），上层会做 min-max 归一后再融合。
///
/// 接口是同步的：模型侧的 embedding 调用几乎都是异步的，实现方自行决定是预先算好
/// 缓存、还是在自己的 runtime 里阻塞等待。让这一层带上 async 会把整个语义层
/// （harness-semantic 至今没有一个 async 函数）都染上 runtime 依赖。
pub trait Recall: Send + Sync {
    fn similarity(&self, question: &str, docs: &[String]) -> Vec<f64>;
}
